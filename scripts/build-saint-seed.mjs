#!/usr/bin/env node
// Writes db/migrations/0002_seed_saints.sql: the first load of Ordo's saints
// into the database, from
//   ordo/saints.json            the bios and the page each came from
//   ordo/calendar-<year>.json   each feast's date (litcal)
//   db/seed/feast-persons.json  who each feast celebrates
//   db/seed/saint-facts.json    death dates and patronages (Wikidata)
// Every row it inserts names its source.
//
// One-off: once applied, the migration is never edited; later changes to the
// data are new migrations (or, from Phase 3, edits in /admin).
//
//   node scripts/build-saint-seed.mjs
import fs from 'node:fs';

const read = f => JSON.parse(fs.readFileSync(f, 'utf8'));
const bios = read('ordo/saints.json');
const persons = read('db/seed/feast-persons.json');
const { _about, ...facts } = read('db/seed/saint-facts.json');
const calendars = fs.readdirSync('ordo').filter(f => /^calendar-\d{4}\.json$/.test(f)).sort().map(f => read(`ordo/${f}`));

const q = s => (s == null ? 'NULL' : `N'${String(s).replace(/'/g, "''")}'`);
const slug = s => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// ── sources ──
const sources = [];
const sourceId = new Map();
function source(kind, title, url, license = null, retrieved = null) {
  if (!sourceId.has(url)) {
    sources.push({ id: sources.length + 1, kind, title, url, license, retrieved });
    sourceId.set(url, sources.length);
  }
  return sourceId.get(url);
}
const litcal = source('litcal', 'Liturgical Calendar API (General Roman Calendar)', 'https://litcal.johnromanodorazio.com', null, null);

function bioSource(b) {
  if (b.source_name === 'Wikipedia') return source('wikipedia', 'Wikipedia', b.source_url, 'CC BY-SA 4.0');
  if (b.source_name === 'Vatican.va') return source('vatican', 'Vatican.va', b.source_url);
  return source('butler-1894', "Summary based on Butler's Lives of the Saints (1894), via catholicsaints.info", b.source_url, 'Public domain (1894)');
}

// ── feasts and their dates ──
const problems = [];
const feasts = Object.keys(persons).sort().map((name, i) => {
  const dates = new Set();
  for (const cal of calendars) for (const [d, e] of Object.entries(cal)) if (e.name === name) dates.add(d.slice(5));
  if (!dates.size) problems.push(`${name}: not in any calendar file`);
  // A fixed feast can move in a year when it collides with a higher day
  // (St Joseph in Holy Week); the earliest date seen is used, and differing
  // dates are reported.
  const [md] = [...dates].sort();
  if (dates.size > 1) problems.push(`${name}: dates ${[...dates].join(', ')}; using ${md}`);
  const b = bios[name];
  return { id: i + 1, name, month: Number(md.slice(0, 2)), day: Number(md.slice(3)), bio: b?.excerpt ?? null, bioSource: b ? bioSource(b) : null };
});

// ── saints, patronages ──
const saintNames = [...new Set(Object.values(persons).flat())].sort();
const saints = saintNames.map((name, i) => {
  const f = facts[name];
  const wd = f ? source('wikidata', `Wikidata: ${f.label ?? f.wikidata}`, f.wikidata_url, 'CC0', f.retrieved) : null;
  return { id: i + 1, name, slug: slug(name), f, wd };
});
const saintId = new Map(saints.map(s => [s.name, s.id]));

const lines = [];
const out = (...l) => lines.push(...l);
out('-- Generated by scripts/build-saint-seed.mjs. Never edit an applied migration;',
  '-- later data changes are new migrations.', '');
out('SET IDENTITY_INSERT dbo.sources ON;');
for (const s of sources) out(`INSERT dbo.sources (id, kind, title, url, license, retrieved_on) VALUES (${s.id}, '${s.kind}', ${q(s.title)}, ${q(s.url)}, ${q(s.license)}, ${s.retrieved ? `'${s.retrieved}'` : 'NULL'});`);
out('SET IDENTITY_INSERT dbo.sources OFF;', '', 'SET IDENTITY_INSERT dbo.saints ON;');
for (const s of saints) {
  const d = s.f?.death;
  out(`INSERT dbo.saints (id, slug, name, wikidata_id, death_year, death_precision, death_source_id) VALUES (${s.id}, '${s.slug}', ${q(s.name)}, ${s.f ? `'${s.f.wikidata}'` : 'NULL'}, ${d ? d.year : 'NULL'}, ${d ? `'${d.precision}'` : 'NULL'}, ${d ? s.wd : 'NULL'});`);
}
out('SET IDENTITY_INSERT dbo.saints OFF;', '', 'SET IDENTITY_INSERT dbo.feasts ON;');
for (const f of feasts) out(`INSERT dbo.feasts (id, calendar_name, month, day, date_source_id, bio, bio_source_id) VALUES (${f.id}, ${q(f.name)}, ${f.month}, ${f.day}, ${litcal}, ${q(f.bio)}, ${f.bioSource ?? 'NULL'});`);
out('SET IDENTITY_INSERT dbo.feasts OFF;', '');
for (const f of feasts) for (const p of persons[f.name]) out(`INSERT dbo.feast_saints (feast_id, saint_id) VALUES (${f.id}, ${saintId.get(p)});`);
out('');
for (const s of saints) for (const p of s.f?.patronages ?? []) out(`INSERT dbo.patronages (saint_id, patronage, wikidata_id, source_id) VALUES (${s.id}, ${q(p.label)}, '${p.wikidata}', ${s.wd});`);

fs.writeFileSync('db/migrations/0002_seed_saints.sql', lines.join('\n') + '\n');
console.log(`sources ${sources.length}, saints ${saints.length}, feasts ${feasts.length}, patronages ${saints.reduce((n, s) => n + (s.f?.patronages?.length ?? 0), 0)}`);
if (problems.length) console.log(`notes:\n  ${problems.join('\n  ')}`);
